(() => {
  let lang = 'vi';
  const supportedLanguages = ['vi', 'en', 'ja', 'es', 'fr', 'ko'];
  try { const saved = localStorage.getItem('lang'); if (supportedLanguages.includes(saved)) lang = saved; } catch {}
  let activeDemo = 'chat';
  const copy = key => LANDING_COPY[key]?.[lang] || key;
  const modal = document.getElementById('login-modal');
  let lastFocus;
  function demo() {
    ['question','answer','source'].forEach((name, i) => {
      document.getElementById(`demo-${name}`).textContent = copy(`demo_${activeDemo}_${['q','a','s'][i]}`);
    });
  }
  function applyLanguage() {
    document.documentElement.lang = lang;
    document.title = copy('title');
    document.querySelector('meta[name="description"]').content = copy('intro');
    document.querySelectorAll('[data-copy]').forEach(el => { el.textContent = copy(el.dataset.copy); });
    document.getElementById('language').value = lang;
    document.querySelectorAll('[data-video]').forEach(el => el.setAttribute('aria-label', copy('play_video')));
    const error = document.getElementById('login-error');
    if (error.dataset.error) error.textContent = copy(error.dataset.error);
    demo();
  }
  document.getElementById('language').addEventListener('change', event => {
    lang = event.target.value;
    try { localStorage.setItem('lang', lang); } catch {}
    applyLanguage();
  });
  document.querySelectorAll('[data-demo]').forEach(button => button.addEventListener('click', () => {
    activeDemo = button.dataset.demo;
    document.querySelectorAll('[data-demo]').forEach(el => el.setAttribute('aria-pressed', String(el === button)));
    demo();
  }));
  document.querySelectorAll('[data-login]').forEach(button => button.addEventListener('click', () => {
    if (window.PB?.authStore.isValid) { window.location.href = 'index.html'; return; }
    lastFocus = button;
    modal.showModal();
    document.getElementById('login-email').focus();
  }));
  document.getElementById('close-login').addEventListener('click', () => modal.close());
  modal.addEventListener('click', event => { if (event.target === modal) { const r = modal.getBoundingClientRect(); if (event.clientX < r.left || event.clientX > r.right || event.clientY < r.top || event.clientY > r.bottom) modal.close(); } });
  modal.addEventListener('close', () => lastFocus?.focus());
  function showError(key) { const el = document.getElementById('login-error'); el.dataset.error = key; el.textContent = copy(key); el.hidden = false; }
  function setBusy(busy) {
    document.getElementById('btn-login-google').disabled = busy;
    const button = document.getElementById('btn-password-login');
    button.disabled = busy;
    button.dataset.copy = busy ? 'busy' : 'password_login';
    button.textContent = copy(button.dataset.copy);
    if (busy) { document.getElementById('login-error').hidden = true; }
  }
  document.getElementById('password-login-form').addEventListener('submit', async event => {
    event.preventDefault();
    if (!window.PB) { showError('unavailable'); return; }
    setBusy(true);
    try {
      await window.PB.collection('tenants').authWithPassword(document.getElementById('login-email').value.trim(), document.getElementById('login-password').value);
      try { localStorage.setItem('loginMethod', 'password'); } catch {}
      // Dashboard resolves memberships and redirects customer-only accounts.
      window.location.href = 'index.html';
    } catch (error) { showError(error?.status === 400 ? 'invalid' : 'error'); }
    finally { setBusy(false); }
  });
  document.getElementById('btn-login-google').addEventListener('click', async () => {
    if (!window.PB) { showError('unavailable'); return; }
    setBusy(true);
    try {
      const methods = await window.PB.collection('tenants').listAuthMethods();
      const provider = (methods.oauth2?.providers || methods.authProviders || []).find(p => p.name === 'google');
      if (!provider) { showError('google_missing'); return; }
      localStorage.setItem('provider', JSON.stringify(provider));
      window.location.href = provider.authUrl + window.location.origin;
    } catch { showError('error'); }
    finally { setBusy(false); }
  });
  document.querySelectorAll('[data-video]').forEach(button => {
    const config = window.LANDING_VIDEOS?.[button.dataset.video];
    if (config?.poster) { button.style.backgroundImage = `url(${JSON.stringify(config.poster)})`; button.style.backgroundSize = 'cover'; button.style.backgroundPosition = 'center'; button.querySelector('.cover-art').hidden = true; }
    if (config?.src) button.querySelector('.video-placeholder').dataset.copy = 'watch_video';
    button.addEventListener('click', () => {
      const card = button.closest('.video-card');
      if (!config?.src) { const status = card.querySelector('.video-status'); status.dataset.copy = 'video_soon'; status.textContent = copy('video_soon'); return; }
      let url;
      try { url = new URL(config.src, location.href); if (!['https:', 'http:'].includes(url.protocol)) throw new Error(); } catch { card.querySelector('.video-status').dataset.copy = 'video_error'; card.querySelector('.video-status').textContent = copy('video_error'); return; }
      let player;
      if (config.type === 'embed') {
        if (!['www.youtube-nocookie.com', 'www.youtube.com', 'player.vimeo.com'].includes(url.hostname)) { card.querySelector('.video-status').dataset.copy = 'video_error'; card.querySelector('.video-status').textContent = copy('video_error'); return; }
        player = document.createElement('iframe'); player.src = url.href; player.title = card.querySelector('h3').textContent; player.allow = 'autoplay; fullscreen; picture-in-picture'; player.allowFullscreen = true;
      } else {
        player = document.createElement('video'); player.controls = true; player.playsInline = true; player.src = url.href; if (config.poster) player.poster = config.poster;
        player.addEventListener('error', () => { card.querySelector('.video-status').dataset.copy = 'video_error'; card.querySelector('.video-status').textContent = copy('video_error'); });
      }
      button.replaceWith(player); player.focus();
      if (player.tagName === 'VIDEO') player.play().catch(() => {});
    });
  });
  applyLanguage();
})();
